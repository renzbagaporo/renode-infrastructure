using System;
using System.Linq;
using System.Threading;

using Antmicro.Renode.Core;
using Antmicro.Renode.Logging;
using Antmicro.Renode.Logging.Profiling;
using Antmicro.Renode.Peripherals.CPU;
using Antmicro.Renode.Peripherals.DMA;

namespace Antmicro.Renode.Peripherals.Miscellaneous
{
    // Counts completed data transactions exposed by the native CPU and DMA
    // models. Native instruction-decode reads are not architectural bus fetches
    // and are deliberately excluded. The functional bus serializes masters, so
    // it supplies no arbitration-delay/contested events; a timing-aware fabric
    // can supply those through NotifyBusAccess when an access actually completes.
    public sealed class RP2040_BUSCTRL : RP2APBPeripheral, IDisposable
    {
        public RP2040_BUSCTRL(IMachine machine, CortexM core0 = null, CortexM core1 = null, RP2040_DMA dma = null)
            : base(machine)
        {
            if(core0 != null && core0 == core1) throw new ArgumentException("Bus masters must be distinct CPUs");
            cores = new[] { core0, core1 }.Where(core => core != null).ToArray();
            this.dma = dma;
            Reset();
        }

        public override void Reset()
        {
            var deferred = Monitor.IsEntered(SyncRoot);
            lock(SyncRoot)
            {
                priority = 0;
                priorityAcknowledged = false;
                Array.Clear(counters, 0, counters.Length);
                for(var i = 0; i < selectors.Length; i++) selectors[i] = 31;
                observationUpdateRequested = 1;
            }
            if(!deferred) UpdateObservation();
        }

        public void Dispose()
        {
            lock(observationSync)
            {
                if(disposed) return;
                disposed = true;
                SetObservation(false);
            }
        }

        // A completion can represent several actual events batched by a bus
        // producer. No event is generated by reading a performance counter.
        public void NotifyBusAccess(ulong address, bool contested = false, uint count = 1)
        {
            var selectedEvent = DecodeAccess(address);
            if(selectedEvent < 0 || count == 0) return;
            lock(SyncRoot)
            {
                if(ResetHeld || disposed) return;
                for(var i = 0; i < selectors.Length; i++)
                {
                    if(selectors[i] != selectedEvent && !(contested && selectors[i] == selectedEvent - 1)) continue;
                    counters[i] = (uint)Math.Min(CounterMask, (ulong)counters[i] + count);
                }
            }
        }

        protected override uint ReadRegister(long offset)
        {
            switch(offset)
            {
            case 0x0: return priority;
            case 0x4: return priorityAcknowledged ? 1u : 0u;
            }
            if(offset >= 0x8 && offset <= 0x24 && (offset & 3) == 0)
            {
                var index = (int)((offset - 8) / 8);
                return (offset & 4) == 0 ? counters[index] : selectors[index];
            }
            this.LogUnhandledRead(offset);
            return 0;
        }

        protected override void WriteRegister(long offset, uint value, AtomicOperation operation)
        {
            switch(offset)
            {
            case 0x0:
                priority = ApplyOperation(priority, value, operation, 0x1111);
                // There are no simultaneous in-flight arbiter requests in the
                // functional bus. All masters therefore observe this update.
                priorityAcknowledged = true;
                return;
            case 0x4:
                return;
            }
            if(offset >= 0x8 && offset <= 0x24 && (offset & 3) == 0)
            {
                var index = (int)((offset - 8) / 8);
                if((offset & 4) == 0) counters[index] = 0;
                else
                {
                    selectors[index] = ApplyOperation(selectors[index], value, operation, 0x1f);
                    observationUpdateRequested = 1;
                }
                return;
            }
            this.LogUnhandledWrite(offset, value);
        }

        protected override void OnAccessCompleted()
        {
            if(Interlocked.Exchange(ref observationUpdateRequested, 0) != 0) UpdateObservation();
        }

        protected override void OnResetHeldChanged()
        {
            observationUpdateRequested = 1;
        }

        private void UpdateObservation()
        {
            lock(observationSync)
            {
                bool enabled;
                lock(SyncRoot) enabled = !disposed && !ResetHeld && selectors.Any(selector => selector < 20);
                SetObservation(enabled);
            }
        }

        private void SetObservation(bool enabled)
        {
            if(observing == enabled) return;
            observing = enabled;
            foreach(var core in cores)
            {
                if(enabled) core.AddMemoryAccessHook(OnCpuMemoryAccess);
                else core.RemoveMemoryAccessHook(OnCpuMemoryAccess);
            }
            if(dma != null)
            {
                if(enabled) dma.BusAccessCompleted += OnDmaBusAccess;
                else dma.BusAccessCompleted -= OnDmaBusAccess;
            }
        }

        private void OnCpuMemoryAccess(ulong pc, MemoryOperation operation, ulong virtualAddress,
            ulong physicalAddress, uint width, ulong value)
        {
            if(operation == MemoryOperation.InsnFetch) return;
            NotifyBusAccess(physicalAddress);
        }

        private void OnDmaBusAccess(ulong address, bool write) => NotifyBusAccess(address);

        private static int DecodeAccess(ulong address)
        {
            if(address < 0x10000000) return 19; // ROM crossbar port, including its decode-error completions.
            if(address < 0x20000000) return 17; // XIP main, register/cache aliases and SSI.
            if(address >= 0x20000000 && address < 0x20040000)
            {
                var bank = (int)((address >> 2) & 3);
                return 15 - bank * 2;
            }
            if(address >= 0x20040000 && address < 0x20041000) return 7;
            if(address >= 0x20041000 && address < 0x20042000) return 5;
            if(address >= 0x21000000 && address < 0x21040000)
            {
                var bank = (int)((address - 0x21000000) >> 16);
                return 15 - bank * 2;
            }
            if(address >= 0x40000000 && address < 0x50000000) return 1;
            if(address >= 0x50000000 && address < 0x60000000) return 3;
            return -1; // SIO/PPB are private processor ports, not this crossbar.
        }

        private uint priority;
        private bool priorityAcknowledged;
        private bool observing;
        private bool disposed;
        private int observationUpdateRequested;
        private readonly object observationSync = new object();
        private readonly uint[] counters = new uint[4];
        private readonly uint[] selectors = new uint[4];
        private readonly CortexM[] cores;
        private readonly RP2040_DMA dma;
        private const ulong CounterMask = 0xffffff;
    }
}
